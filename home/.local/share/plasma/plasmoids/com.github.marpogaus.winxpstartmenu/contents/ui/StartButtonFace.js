function parse(rows) {
    return rows.map(row => row.split(" ").map(hex => [0, 2, 4].map(i => parseInt(hex.substr(i, 2), 16))));
}
var tables = { "normal": parse(NORMAL), "hover": parse(HOVER), "pressed": parse(PRESSED) };
var ROW_COUNT = NORMAL.length;
var MIDDLE = COLUMNS.findIndex(([kind]) => kind === "M");

// How far the right edge pulls back from the middle at row y, fitted to
// XP's button: a power curve, fuller at the top than at the bottom
function pullBack(y, h) {
    const d = Math.abs(y - h / 2) / (h / 2);
    return h * (y < h / 2 ? 0.142 * Math.pow(d, 1.9) : 0.13 * Math.pow(d, 1.45));
}

function mix(a, b, t) {
    return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
}

// Colour samples of row y of an h px button (between the table's rows)
function rowAt(table, y, h) {
    const r = Math.max(0, Math.min(ROW_COUNT - 1, (y + 0.5) * ROW_COUNT / h - 0.5));
    const top = Math.floor(r);
    const bottom = Math.min(ROW_COUNT - 1, top + 1);
    return table[top].map((c, i) => mix(c, table[bottom][i], r - top));
}

function css(c) {
    return "rgb(" + Math.round(c[0]) + "," + Math.round(c[1]) + "," + Math.round(c[2]) + ")";
}

